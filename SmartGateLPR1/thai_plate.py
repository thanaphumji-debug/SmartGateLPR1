"""
แปลงข้อความดิบที่ได้จาก OCR ให้เป็น "เลขทะเบียน + จังหวัด" ของป้ายทะเบียนไทย

ทำไมต้องมีไฟล์นี้
-----------------
โมเดล PaddleOCR ภาษาไทย (th_PP-OCRv5_mobile_rec) เป็นโมเดลอ่านข้อความไทย
ทั่วไป ไม่ได้เทรนมาเฉพาะป้ายทะเบียน ผลที่ได้จึงมักมีสัญญาณรบกวน เช่น
อ่านเลขเป็นตัวอักษรละติน (0 -> O), ติดขอบป้ายมาเป็นขีด, หรือสะกดชื่อจังหวัด
เพี้ยนไปหนึ่งสองตัว  โมดูลนี้ทำหน้าที่ "ดัดให้เข้ารูป" ตามกติกาของป้ายไทย
ซึ่งช่วยความแม่นยำได้มากโดยไม่ต้องเทรนโมเดลใหม่

ทุกฟังก์ชันในไฟล์นี้เป็น pure function (ไม่พึ่ง OpenCV / torch / paddle)
จึงทดสอบแยกได้ด้วย  python thai_plate.py
"""

