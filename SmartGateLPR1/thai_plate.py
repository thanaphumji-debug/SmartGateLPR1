if __name__ == "__main__":
    ok = fail = 0

    def check(got, want, label):
        global ok, fail
        if got == want:
            ok += 1
        else:
            fail += 1
            print(f"  ❌ {label}\n     ได้: {got!r}\n     ควรได้: {want!r}")

    print("— ทดสอบ normalize_plate_number —")
    for src, want in [
        ("กย3779", "กย3779"),
        ("กย 3779", "กย3779"),
        ("กย-3779", "กย3779"),
        ("๑กก๑๒๓๔", "1กก1234"),          # เลขไทย
        ("1กก 1234", "1กก1234"),          # ป้ายรุ่นใหม่ มีเลขนำหน้า
        ("กยO779", "กย0779"),             # OCR อ่านเลข 0 เป็นอักษร O
        ("ขข123", "ขข123"),
        ("กทม", ""),                      # ไม่มีตัวเลข = ไม่ใช่ทะเบียน
        ("เชียงใหม่", ""),                 # ชื่อจังหวัด ไม่ใช่ทะเบียน
        ("", ""),
    ]:
        check(normalize_plate_number(src), want, f"normalize_plate_number({src!r})")

    print("— ทดสอบ match_province —")
    for src, want in [
        ("กรุงเทพมหานคร", "กรุงเทพมหานคร"),
        ("กรุงเทพ", "กรุงเทพมหานคร"),         # ชื่อย่อ
        ("เชียงใหม่", "เชียงใหม่"),
        ("เชียงใหม", "เชียงใหม่"),             # สะกดขาดไปหนึ่งตัว
        ("นครราชสึมา", "นครราชสีมา"),          # สระเพี้ยน
        ("ราชสีมา", "นครราชสีมา"),             # อ่านได้แค่บางส่วน
        ("จนบุรี", "กาญจนบุรี"),               # อ่านขาดครึ่งหน้า (โดนบัง/ตัดขอบภาพ)
                                               # ก่อนแก้: จับผิดเป็น "จันทบุรี" เพราะ
                                               # fuzzy ratio ทั้งคำ (0.86) ชนะไปก่อนที่จะ
                                               # เช็ค substring ซึ่งตรงกับ "กาญจนบุรี" เป๊ะ
        ("3779", ""),                          # ตัวเลขล้วน
        ("ก", ""),                             # สั้นเกินไป
    ]:
        check(match_province(src)[0], want, f"match_province({src!r})")

    print("— ทดสอบ parse_plate_lines (ผลรวมแบบที่ OCR ส่งมาจริง) —")
    res = parse_plate_lines([("กย 3779", 0.94, 5.0), ("นครราชสีมา", 0.88, 40.0)])
    check(res["plate"], "กย3779", "ป้าย 2 บรรทัดปกติ (เลขทะเบียน)")
    check(res["province"], "นครราชสีมา", "ป้าย 2 บรรทัดปกติ (จังหวัด)")

    res = parse_plate_lines([("เชียงใหม", 0.71, 42.0), ("1กก1234", 0.96, 6.0)])
    check(res["plate"], "1กก1234", "บรรทัดสลับลำดับ (เลขทะเบียน)")
    check(res["province"], "เชียงใหม่", "บรรทัดสลับลำดับ (จังหวัด)")

    res = parse_plate_lines([])
    check(res["plate"], "", "ไม่มีบรรทัดเลย")

    print(f"\nผ่าน {ok} / ไม่ผ่าน {fail}")
    raise SystemExit(1 if fail else 0)
